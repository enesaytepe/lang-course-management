using LanguageCourseManagement.Application.Persistence;
using Microsoft.EntityFrameworkCore.Storage;

namespace LanguageCourseManagement.Infrastructure.Repositories;

public sealed class EfTransactionManager : ITransactionManager
{
    private readonly AppDbContext _context;
    private IDbContextTransaction? _transaction;

    public EfTransactionManager(AppDbContext context)
    {
        _context = context;
    }

    public async Task BeginTransactionAsync(CancellationToken cancellationToken = default)
    {
        _transaction = await _context.Database.BeginTransactionAsync(cancellationToken);
    }

    public async Task CommitAsync(CancellationToken cancellationToken = default)
    {
        if (_transaction is not null)
        {
            await _transaction.CommitAsync(cancellationToken);
            await _transaction.DisposeAsync();
            _transaction = null;
        }
    }

    public async Task RollbackAsync(CancellationToken cancellationToken = default)
    {
        if (_transaction is not null)
        {
            await _transaction.RollbackAsync(cancellationToken);
            await _transaction.DisposeAsync();
            _transaction = null;
        }
    }
}
